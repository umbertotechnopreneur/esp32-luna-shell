"""Convert the versioned cloud definition and palette into immutable firmware tables."""

import hashlib
import json
from cody_rig_contract import ROOT, load_contract


# value is a finite normalized coordinate to emit as an unambiguous C++ float.
def cpp_float(value):
    return f"{float(value):.9f}f"


# No parameters: conversion only; does not configure, compile, run or contact a device.
def main():
    rig, palette = load_contract()
    names = {point["name"]: index for index, point in enumerate(rig["points"])}
    channels = {channel["name"]: index for index, channel in enumerate(rig["channels"])}
    roles = {"anchor": 0, "knot": 1, "handle": 2}
    lines = ['// Generated by scripts/generate_cody_rig.py; edit assets/cody/cody.yaml instead.', '#pragma once', '#include "CODY_rig.hpp"', 'namespace CODY::Data {']
    lines += ['inline constexpr PointDefinition points[] = {']
    for point in rig["points"]:
        floats = ', '.join(cpp_float(value) for value in point["position"] + point["delta"])
        lines.append(f'    {{{json.dumps(point["name"])}, {floats}, {names.get(point["parent"], -1)}, {channels.get(point["channel"], -1)}, {roles[point["role"]]}}},')
    lines += ['};', 'inline constexpr CurveDefinition curves[] = {']
    for curve in rig["curves"]:
        lines.append('    {{' + ', '.join(str(names[name]) for name in curve["points"]) + '}},')
    lines += ['};', 'inline constexpr PathDefinition paths[] = {']
    for path in rig["paths"]:
        lines.append(f'    {{{path["first_curve"]}, {path["curve_count"]}, {path["paint"][0]}, {path["paint"][1]}, {cpp_float(path["stroke"])}, {channels.get(path["visible"], -1)}}},')
    lines += ['};', 'inline constexpr uint16_t palette[256] = {']
    for start in range(0, 256, 8):
        lines.append('    ' + ', '.join(entry["rgb565"] for entry in palette["entries"][start:start+8]) + ',')
    lines += ['};', 'inline constexpr float channel_min[] = {' + ', '.join(cpp_float(v['minimum']) for v in rig['channels']) + '};', 'inline constexpr float channel_max[] = {' + ', '.join(cpp_float(v['maximum']) for v in rig['channels']) + '};', 'inline constexpr const char *channel_names[] = {' + ', '.join(json.dumps(v['name']) for v in rig['channels']) + '};']
    for phase, values in rig['boot_channels'].items():
        lines.append(f'inline constexpr Channels {phase} = {{{{{", ".join(cpp_float(v) for v in values)}}}}};')
    lines.append('inline constexpr Channels defaults = {{' + ', '.join(cpp_float(channel['default']) for channel in rig['channels']) + '}};')
    controls = rig['contour']['controls']
    lines.append('inline constexpr ContourControls contour_defaults = {{' + ', '.join(cpp_float(control['default']) for control in controls) + '}};')
    for label, key in (('min', 'minimum'), ('max', 'maximum')):
        lines.append(f'inline constexpr float contour_{label}[] = {{' + ', '.join(cpp_float(control[key]) for control in controls) + '};')
    lines.append('inline constexpr const char *contour_names[] = {' + ', '.join(json.dumps(control['name']) for control in controls) + '};')
    lines.append('inline constexpr float contour_transition_seconds = ' + cpp_float(rig['contour']['transition_seconds']) + ';')
    lines.append('inline constexpr ContourLobeDefinition contour_lobes[] = {')
    for lobe in rig['contour']['lobes']:
        values = lobe['direction'] + [lobe['fullness'], lobe['wave'], lobe['phase_turns']]
        lines.append('    {' + str(names[lobe['point']]) + ', ' + ', '.join(cpp_float(value) for value in values) + '},')
    lines.append('};')
    lobe_indices = {lobe['point']: index for index, lobe in enumerate(rig['contour']['lobes'])}
    lines.append('inline constexpr int8_t point_contour_lobe[] = {' + ', '.join(str(lobe_indices.get(point['name'], -1)) for point in rig['points']) + '};')
    for role, slot in rig['style']['debug'].items():
        lines.append(f'inline constexpr uint8_t debug_{role} = {slot};')
    lines.append(f'inline constexpr uint8_t back_top = {rig["style"]["back"]["fill"][0]}, back_bottom = {rig["style"]["back"]["fill"][1]}, back_ink = {rig["style"]["back"]["ink"]};')
    lines.append('inline constexpr Transform placement = {' + ', '.join(cpp_float(rig['default_transform'][key]) for key in ('x','y','scale')) + '};')
    lines.append('inline constexpr const char *character_name = ' + json.dumps(rig['character']['name'], ensure_ascii=True) + ';')
    lines += ['inline constexpr EntityDefinition entities[] = {']
    for name, entity in rig['entities'].items():
        lines.append(f'    {{{json.dumps(name)}, {json.dumps(entity["label"])}, {names[entity["anchor"]]}}},')
    lines.append('};')
    lines += ['}  // namespace CODY::Data', '']
    output = ROOT / 'assets/cody/rig/generated'
    output.mkdir(parents=True, exist_ok=True)
    (output / 'cloud_rig_data.hpp').write_text('\n'.join(lines), encoding='utf-8')
    manifest = {'schema':'cody.rig.generated.v1', 'points':len(rig['points']), 'curves':len(rig['curves']), 'paths':len(rig['paths']), 'subdivisions':12, 'palette_slots':256,
                'contour_controls':len(controls), 'contour_lobes':len(rig['contour']['lobes']),
                'source_sha256':hashlib.sha256((ROOT/'assets/cody/cody.yaml').read_bytes()).hexdigest(),
                'palette_sha256':hashlib.sha256((ROOT/'assets/cody/palette/palette256.json').read_bytes()).hexdigest()}
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')
    print(f'Generated {output / "cloud_rig_data.hpp"}')


if __name__ == '__main__':
    main()
