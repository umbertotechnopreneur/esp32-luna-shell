#!/usr/bin/env python3
"""Package the Imagegen boot sources into flash-owned indexed RGB565 resources.

This converts an existing asset; it does not configure or validate firmware.
The generated PNG remains unchanged. Pillow is a host asset-tool dependency.
"""

import hashlib
import json
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
BOOT_DIRECTORY = ROOT / "assets/cody/boot"
OUTPUT = BOOT_DIRECTORY / "generated"
WIDTH = 466
HEIGHT = 466


# red: Eight-bit red channel from the source palette.
# green: Eight-bit green channel from the source palette.
# blue: Eight-bit blue channel from the source palette.
def rgb565(red: int, green: int, blue: int) -> int:
    return ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)


# values: Unsigned integer array to emit as immutable C++ data.
# digits: Hexadecimal width for one value in the requested array type.
# columns: Number of array values per source line.
def array_lines(values: list[int], digits: int, columns: int) -> str:
    return "\n".join(
        "    " + ", ".join(f"0x{value:0{digits}x}" for value in values[start:start + columns]) + ","
        for start in range(0, len(values), columns)
    )


# source_name: Source PNG filename inside the boot asset directory.
# output_stem: Basename of the generated C++ source and header.
# symbol: Public immutable resource symbol inside CODY_asset.
# Raises OSError for asset I/O errors and ValueError for an unsupported source.
def package_image(source_name: str, output_stem: str, symbol: str) -> dict:
    source_path = BOOT_DIRECTORY / source_name
    source_bytes = source_path.read_bytes()
    with Image.open(source_path) as source:
        if source.width != source.height:
            raise ValueError("The boot source must be square; no implicit crop is allowed")
        if "A" in source.getbands() and source.getchannel("A").getextrema() != (255, 255):
            raise ValueError("The black boot source must be opaque")
        source_dimensions = [source.width, source.height]
        resized = source.convert("RGB").resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)

    # Quantization belongs to resource encoding. Black has a dedicated index and
    # remains exact; neither a PNG decoder nor a palette-sized framebuffer is
    # needed on the ESP. No dithering or runtime image parsing is introduced.
    indexed = resized.quantize(colors=63, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    encoded_palette = indexed.getpalette()
    palette = [0]
    color_indices = {0: 0}
    remap = {}
    source_indices = indexed.tobytes()
    for source_index in sorted(set(source_indices)):
        offset = source_index * 3
        color = rgb565(*encoded_palette[offset:offset + 3])
        if color not in color_indices:
            color_indices[color] = len(palette)
            palette.append(color)
        remap[source_index] = color_indices[color]
    source_rgb = resized.tobytes()
    pixels = [
        0 if rgb565(*source_rgb[position * 3:position * 3 + 3]) == 0 else remap[index]
        for position, index in enumerate(source_indices)
    ]

    runs = []
    row_offsets = [0]
    for row in range(HEIGHT):
        row_pixels = pixels[row * WIDTH:(row + 1) * WIDTH]
        position = 0
        while position < WIDTH:
            color_index = row_pixels[position]
            end = position + 1
            while end < WIDTH and row_pixels[end] == color_index:
                end += 1
            count = end - position
            runs.extend((count & 0xff, count >> 8, color_index))
            position = end
        row_offsets.append(len(runs))

    OUTPUT.mkdir(parents=True, exist_ok=True)
    header = f'''// Generated by scripts/package_cody_boot.py from the unchanged Imagegen PNG.
#pragma once
#include "CODY2D.hpp"

namespace CODY_asset {{
extern const CODY2D::IndexedRleImage {symbol};
}}
'''
    cpp = f'''// Generated by scripts/package_cody_boot.py; immutable data remains in flash.
#include "{output_stem}.hpp"

namespace CODY_asset {{
namespace {{
const uint16_t palette[] = {{
{array_lines(palette, 4, 12)}
}};
const uint32_t row_offsets[] = {{
{array_lines(row_offsets, 8, 8)}
}};
const uint8_t runs[] = {{
{array_lines(runs, 2, 24)}
}};
}}
const CODY2D::IndexedRleImage {symbol}{{
    {WIDTH}, {HEIGHT}, {len(palette)}, palette, row_offsets, runs, sizeof(runs)
}};
}}
'''
    (OUTPUT / f"{output_stem}.hpp").write_text(header, encoding="utf-8", newline="\n")
    (OUTPUT / f"{output_stem}.cpp").write_text(cpp, encoding="utf-8", newline="\n")
    resource_bytes = len(palette) * 2 + len(row_offsets) * 4 + len(runs)
    return {
        "source": source_path.relative_to(ROOT).as_posix(),
        "symbol": symbol,
        "source_sha256": hashlib.sha256(source_bytes).hexdigest(),
        "source_dimensions": source_dimensions,
        "width": WIDTH,
        "height": HEIGHT,
        "encoding": "row-indexed-rle-rgb565",
        "run_format": "uint16 little-endian pixel count, uint8 palette index",
        "palette_colors": len(palette),
        "black_palette_index": 0,
        "rle_bytes": len(runs),
        "resource_data_bytes": resource_bytes,
    }


# Raises OSError for asset I/O errors and ValueError for an unsupported source.
def main() -> None:
    images = [
        package_image("cody-sleep-blue.png", "cody_sleep_blue", "sleeping_blue"),
        package_image("cody-waking-blue.png", "cody_waking_blue", "waking_blue"),
        package_image("cody-ready-blue.png", "cody_ready_blue", "ready_blue"),
    ]
    total_bytes = sum(image["resource_data_bytes"] for image in images)
    manifest = {
        "images": images,
        "resource_data_bytes": total_bytes,
        "renderer_strip_rows": 8,
        "renderer_strip_bytes": WIDTH * 8 * 2,
        "note": "Source encoding sizes only; compiled firmware size and hardware behavior are unverified.",
    }
    (OUTPUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"Cody boot resources: {WIDTH}x{HEIGHT}, {total_bytes} data bytes for sleeping/waking/ready; sources preserved")


if __name__ == "__main__":
    main()
