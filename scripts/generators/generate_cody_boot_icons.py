"""Package the retained four-cell BOOT icon master as bounded indexed flash data."""

from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "cody-device/assets/cody/boot-menu-icons"
NAMES = ("settings", "events", "counters", "about")


# values: Immutable integer data in firmware order.
# Exception: Propagates formatting errors.
def lines(values):
    return "\n".join("    " + ", ".join(f"0x{value:02x}" for value in values[i:i + 16]) + ","
                     for i in range(0, len(values), 16))


# No parameters: reads the retained atlas and writes a deterministic flash header.
# Exception: Propagates image, geometry, quantization or file errors.
def main():
    with Image.open(ASSETS / "source/atlas.png") as source:
        atlas = source.convert("RGBA")
    if atlas.width != atlas.height or atlas.width % 2:
        raise ValueError("BOOT icon atlas must be square with four equal cells")
    side = atlas.width // 2
    sections = []
    for index, name in enumerate(NAMES):
        x, y = (index % 2) * side, (index // 2) * side
        image = atlas.crop((x, y, x + side, y + side)).resize((32, 32), Image.Resampling.LANCZOS)
        alpha = image.getchannel("A")
        quantized = image.convert("RGB").quantize(colors=15, method=Image.Quantize.MEDIANCUT,
                                                  dither=Image.Dither.NONE)
        palette = quantized.getpalette()
        colors = [0]
        for i in range(15):
            r, g, b = palette[3 * i:3 * i + 3]
            colors.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
        pixels = [value + 1 if opacity >= 64 else 0
                  for value, opacity in zip(quantized.tobytes(), alpha.tobytes())]
        packed = [(pixels[i] << 4) | pixels[i + 1] for i in range(0, len(pixels), 2)]
        sections.append(f"inline constexpr uint16_t {name}_palette[16] = {{\n    " +
                        ", ".join(f"0x{color:04x}" for color in colors) +
                        f",\n}};\ninline constexpr uint8_t {name}_cells[512] = {{\n" +
                        lines(packed) + "\n};\n")
    output = ASSETS / "generated/boot_icons.hpp"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("// Generated by scripts/device.ps1 generate -Generator cody-boot-icons.\n"
                      "#pragma once\n#include <cstdint>\n\nnamespace CODY::BootIconData {\n" +
                      "\n".join(sections) + "} // namespace CODY::BootIconData\n",
                      encoding="utf-8", newline="\n")
    print(f"Generated {output.relative_to(ROOT)}: four indexed 32x32 icons")


if __name__ == "__main__":
    main()
