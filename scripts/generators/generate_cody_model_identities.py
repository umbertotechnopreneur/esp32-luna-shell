"""Generate bounded model backgrounds from their original image masters."""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "cody-device/assets/cody/model-identities"


# values: Immutable integer data in firmware order.
# width: Number of integers written per source line.
# Exception: Propagates formatting errors.
def lines(values, width):
    return "\n".join("    " + ", ".join(f"0x{value:02x}" for value in values[i:i + width]) + ","
                     for i in range(0, len(values), width))


# name: Fixed, locally authored identity and matching source filename.
# Exception: Propagates image, quantization and file errors.
def generate(name):
    with Image.open(ASSETS / f"source/{name}.png") as image:
        image = image.convert("RGBA").resize((64, 64), Image.Resampling.LANCZOS)
    alpha = image.getchannel("A")
    rgb = image.convert("RGB")
    quantized = rgb.quantize(colors=15, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    palette = quantized.getpalette()
    colors = [0]
    for i in range(15):
        r, g, b = palette[3 * i:3 * i + 3]
        colors.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    pixels = [index + 1 if opacity >= 64 else 0
              for index, opacity in zip(quantized.tobytes(), alpha.tobytes())]
    packed = [(pixels[i] << 4) | pixels[i + 1] for i in range(0, len(pixels), 2)]
    header = (
        "// Generated by scripts/device.ps1 generate -Generator cody-model-identities.\n"
        "#pragma once\n#include <cstdint>\n\nnamespace CODY::ModelIdentityData {\n"
        f"inline constexpr uint16_t {name}_palette[16] = {{\n    "
        + ", ".join(f"0x{color:04x}" for color in colors) + ",\n};\n"
        f"inline constexpr uint8_t {name}_cells[2048] = {{\n" + lines(packed, 16) +
        "\n};\n} // namespace CODY::ModelIdentityData\n"
    )
    output = ASSETS / f"generated/{name}.hpp"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(header, encoding="utf-8", newline="\n")
    print(f"Generated {output.relative_to(ROOT)}: 64x64, 16 slots, 2048 packed bytes")


# No parameters: Package all explicitly authored identities.
# Exception: Propagates image, quantization and file errors.
def main():
    for name in ("terra", "sol", "luna", "astra"):
        generate(name)


if __name__ == "__main__":
    main()
