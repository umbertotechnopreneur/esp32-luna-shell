"""Synthetic tests for the authenticated Studio animation protocol."""

from dataclasses import replace
from pathlib import Path
import re
import threading
import unittest
from unittest.mock import Mock, patch

import ccp_activity as activity
import ccp_animation as animation
import ccp_server as ccp


class AnimationContractTests(unittest.TestCase):
    # self: Isolated responder using synthetic credentials and a mocked UDP socket.
    def setUp(self):
        self.device = "abcdef012345"
        self.key = bytes(range(32))
        self.state = Mock(pc_id="a" * 32)
        self.state.retained_keys.return_value = ccp.RetainedKeys(self.key, None)
        self.socket = Mock()
        self.responder = ccp.CompanionResponder(self.state, self.socket, activity.ActivityStore())
        self.source = ("192.0.2.42", ccp.DEVICE_PORT)
        self.peer = ccp.EventPeer("b" * 32, self.key, self.source, ccp.time.monotonic())
        self.responder._event_peers[self.device] = self.peer
        self.requests = self.responder.animations

    # self: Owner of the synthetic paired device and its current READY nonce.
    # proof: Optional replacement for testing a forged signature.
    def capability(self, proof=None):
        names = ("device", "pc", "nonce", "animation")
        values = (self.device, self.state.pc_id, self.peer.nonce, "1")
        return ccp.encode_datagram("ANIMCAP", list(zip(names, values)) + [
            ("proof", proof if proof is not None else ccp.make_proof(self.key, "anim-cap", *values))
        ])

    # self: Test fixture receiving a command from the production responder.
    # packet: Bounded ANIM request generated by the production encoder.
    # destination: Authenticated endpoint selected by the broker.
    # status: Simulated device's signed status.
    # error: Simulated device's signed numeric result.
    def acknowledge(self, packet, destination, status="applied", error="0"):
        kind, fields = ccp.parse_datagram(packet)
        self.assertEqual(kind, "ANIM")
        self.assertEqual(destination, self.source)
        command = tuple(fields[name] for name in animation.COMMAND_FIELDS)
        self.assertEqual(fields["proof"], ccp.make_proof(self.key, "anim", *command))
        values = (*command, status, error)
        ack = ccp.encode_datagram("ANIMACK", list(zip(animation.ACK_FIELDS, values)) + [
            ("proof", ccp.make_proof(self.key, "anim-ack", *values))
        ])
        self.responder._handle_datagram(ack, destination)

    # self: One device with a fresh authenticated capability for every operation.
    # Raises AssertionError if commands, proofs, results or nonce consumption diverge.
    def test_all_operations_use_signed_single_use_capabilities(self):
        self.socket.sendto.side_effect = self.acknowledge
        for index, operation in enumerate(("select", "play", "pause", "restart", "normal")):
            with self.subTest(operation=operation):
                self.peer = replace(self.peer, nonce=f"{index + 1:032x}", observed_at=ccp.time.monotonic())
                self.responder._event_peers[self.device] = self.peer
                capability = self.capability()
                self.responder._handle_datagram(capability, self.source)
                result = self.requests.request("listening_question", operation)
                self.assertEqual(result, {"device_id": self.device, "scene": "listening_question",
                                          "op": operation, "status": "applied", "error": 0})
                self.responder._handle_datagram(capability, self.source)
                self.assertNotIn(self.device, self.requests._peers)
        self.assertEqual(self.socket.sendto.call_count, 5)

    # self: Capability admission using a real active key and READY endpoint.
    # Raises AssertionError if forged, stale, unpaired, or wrong-endpoint data is admitted.
    def test_capability_requires_current_pairing_nonce_and_endpoint(self):
        with self.assertRaisesRegex(ValueError, "authentication failed"):
            self.responder._handle_datagram(self.capability("0" * 64), self.source)
        with self.assertRaisesRegex(ValueError, "authentication failed"):
            self.responder._handle_datagram(self.capability(), (self.source[0], self.source[1] + 1))
        self.responder._event_peers[self.device] = replace(self.peer, nonce="c" * 32)
        with self.assertRaisesRegex(ValueError, "authentication failed"):
            self.responder._handle_datagram(self.capability(), self.source)
        self.responder._event_peers[self.device] = replace(
            self.peer, observed_at=ccp.time.monotonic() - ccp.LIVENESS_TIMEOUT_SECONDS - 1)
        with self.assertRaisesRegex(ValueError, "authentication failed"):
            self.responder._handle_datagram(self.capability(), self.source)
        self.responder._event_peers[self.device] = self.peer
        self.state.retained_keys.return_value = ccp.RetainedKeys(None, None)
        with self.assertRaisesRegex(ValueError, "authentication failed"):
            self.responder._handle_datagram(self.capability(), self.source)
        self.assertFalse(self.requests._peers)
        self.socket.sendto.assert_not_called()

    # self: A command awaiting its one authenticated acknowledgement.
    # Raises AssertionError if a forged, mismatched, or stale response can complete it.
    def test_ack_rejects_tampering_before_accepting_real_result(self):
        self.responder._handle_datagram(self.capability(), self.source)

        # packet: Request produced by the actual broker.
        # destination: Socket-observed destination for the active peer.
        def receive(packet, destination):
            _, command = ccp.parse_datagram(packet)
            values = tuple(command[name] for name in animation.COMMAND_FIELDS) + ("applied", "0")
            fields = dict(zip(animation.ACK_FIELDS, values))
            fields["proof"] = ccp.make_proof(self.key, "anim-ack", *values)
            for changes, source in (({"proof": "0" * 64}, destination),
                                    ({"id": "c" * 32}, destination),
                                    ({"scene": "sleep"}, destination),
                                    ({"error": "-1"}, destination),
                                    ({}, (destination[0], destination[1] + 1))):
                with self.subTest(changes=changes, source=source):
                    with self.assertRaises(ValueError):
                        self.requests.accept_ack({**fields, **changes}, source)
                    self.assertIsNone(self.requests._requests[self.device]["result"])
            self.responder._handle_datagram(
                ccp.encode_datagram("ANIMACK", list(fields.items())), destination)

        self.socket.sendto.side_effect = receive
        self.assertEqual(self.requests.request("idle", "select")["status"], "applied")

    # self: Expired and duplicated signed acknowledgements must not revive a request.
    # Raises AssertionError if a late result completes a missing or expired transaction.
    def test_ack_rejects_expiry_and_duplicate_delivery(self):
        self.responder._handle_datagram(self.capability(), self.source)
        captured = []

        # packet: Command generated by the production broker.
        # destination: Authenticated device endpoint.
        def receive(packet, destination):
            _, command = ccp.parse_datagram(packet)
            values = tuple(command[name] for name in animation.COMMAND_FIELDS) + ("applied", "0")
            ack = ccp.encode_datagram("ANIMACK", list(zip(animation.ACK_FIELDS, values)) + [
                ("proof", ccp.make_proof(self.key, "anim-ack", *values))
            ])
            captured.append(ack)
            deadline = self.requests._requests[self.device]["deadline"]
            with patch.object(animation.time, "monotonic", return_value=deadline):
                with self.assertRaisesRegex(ValueError, "no matching live request"):
                    self.responder._handle_datagram(ack, destination)
            self.responder._handle_datagram(ack, destination)

        self.socket.sendto.side_effect = receive
        self.assertEqual(self.requests.request("idle", "select")["status"], "applied")
        with self.assertRaisesRegex(ValueError, "no matching live request"):
            self.responder._handle_datagram(captured[0], self.source)

    # self: Signed device rejection and lost acknowledgement fixtures.
    # Raises AssertionError if failure is coerced to success or a lost packet is retried.
    def test_device_rejection_and_timeout_remain_distinct(self):
        self.responder._handle_datagram(self.capability(), self.source)
        self.socket.sendto.side_effect = lambda packet, source: self.acknowledge(packet, source, "rejected", "-1")
        rejected = self.requests.request("sleep", "select")
        self.assertEqual((rejected["status"], rejected["error"]), ("rejected", -1))
        self.peer = replace(self.peer, nonce="c" * 32, observed_at=ccp.time.monotonic())
        self.responder._event_peers[self.device] = self.peer
        self.responder._handle_datagram(self.capability(), self.source)
        self.socket.sendto.side_effect = None
        with patch.object(threading.Event, "wait", return_value=False):
            unknown = self.requests.request("sleep", "play")
        self.assertEqual(unknown["status"], "unknown")
        self.assertEqual(self.socket.sendto.call_count, 2)
        self.assertNotIn(self.device, self.requests._requests)

    # self: Failed datagram transmission consumes the current nonce without retry.
    # Raises AssertionError if a socket failure becomes success or leaves a pending request.
    def test_transport_error_retires_request_without_replay(self):
        self.responder._handle_datagram(self.capability(), self.source)
        self.socket.sendto.side_effect = OSError("synthetic send failure")
        with self.assertRaisesRegex(OSError, "synthetic send failure"):
            self.requests.request("idle", "select")
        self.assertNotIn(self.device, self.requests._requests)
        self.responder._handle_datagram(self.capability(), self.source)
        self.assertNotIn(self.device, self.requests._peers)
        self.socket.sendto.assert_called_once()

    # self: Local validation before transmission and physical-target selection.
    # Raises AssertionError if unknown commands or multiple devices send any datagram.
    def test_invalid_inputs_and_ambiguous_devices_never_send(self):
        for scene, operation in ((None, "play"), ("invalid", "play"), ("idle", None), ("idle", "stop")):
            with self.subTest(scene=scene, operation=operation):
                with self.assertRaises(ValueError):
                    self.requests.request(scene, operation)
        self.responder._handle_datagram(self.capability(), self.source)
        other = "123456abcdef"
        second = replace(self.peer, source=("192.0.2.43", ccp.DEVICE_PORT))
        self.responder._event_peers[other] = second
        values = (other, self.state.pc_id, second.nonce, "1")
        capability = ccp.encode_datagram("ANIMCAP", list(zip(("device", "pc", "nonce", "animation"), values))
            + [("proof", ccp.make_proof(self.key, "anim-cap", *values))])
        self.responder._handle_datagram(capability, second.source)
        with self.assertRaisesRegex(ValueError, "Multiple physical"):
            self.requests.request("idle", "select")
        self.socket.sendto.assert_not_called()

    # self: No eligible device after waiting for a current capability.
    # Raises AssertionError if the broker fabricates a result or sends to a simulated target.
    def test_missing_capability_and_simulated_device_are_not_targets(self):
        self.peer = replace(self.peer, source=("127.0.0.1", ccp.DEVICE_PORT), observed_at=100.0)
        self.source = self.peer.source
        self.responder._event_peers[self.device] = self.peer
        with patch.object(ccp.time, "monotonic", return_value=100.0):
            self.responder._handle_datagram(self.capability(), self.source)
        with patch.object(animation.time, "monotonic", side_effect=(100.0, 111.0)):
            with self.assertRaisesRegex(ValueError, "No fresh animation capability"):
                self.requests.request("idle", "select")
        self.socket.sendto.assert_not_called()

    # self: Cross-language identities must retain the firmware enum ordering.
    # Raises AssertionError if the wire catalog can address a different scene or operation.
    def test_firmware_wire_names_match_enum_order_and_broker(self):
        root = Path(__file__).resolve().parents[2]
        network = (root / "cody-device/components/LUNASHELL_platform/src/network/LUNASHELL_codex_link.cpp").read_text(encoding="utf-8")
        header = (root / "cody-device/components/LUNASHELL_platform/include/LUNASHELL_codex_debug.hpp").read_text(encoding="utf-8")
        for array_name, enum_name, broker_values in (
            ("scenes", "CodexAnimationScene", animation.SCENES),
            ("operations", "CodexAnimationOperation", animation.OPERATIONS),
        ):
            with self.subTest(catalog=array_name):
                array_match = re.search(rf"static constexpr const char \*{array_name}\[\] = \{{([^}}]+)\}};", network)
                enum_match = re.search(rf"enum class {enum_name}\s*:\s*uint8_t\s*\{{([^}}]+)\}};", header)
                self.assertIsNotNone(array_match)
                self.assertIsNotNone(enum_match)
                wire_names = re.findall(r'"([a-z_]+)"', array_match.group(1))
                enum_names = [item.strip() for item in enum_match.group(1).split(",") if item.strip()]
                self.assertEqual(set(wire_names), broker_values)
                self.assertEqual(len(wire_names), len(broker_values))
                self.assertEqual(enum_names, ["".join(part.capitalize() for part in name.split("_"))
                                              for name in wire_names])
